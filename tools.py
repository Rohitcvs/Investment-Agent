import json
import os
import re
from typing import Optional

from langchain_core.tools import BaseTool

"""
Tools used by the investment analysis agents.

Heavy libraries (yfinance, pandas-ta, ddgs) are imported inside each tool,
so the rest of the project (and the tests) can load without them.
"""

DISCLAIMER = "This report is generated by an AI and is for informational purposes only. It is not financial advice."


class StockDataTool(BaseTool):
    """Fetches one year of price data and returns a compact summary."""
    name: str = "Stock_Data_Fetcher"
    description: str = (
        "Fetches one year of historical stock data for a ticker and returns a summary "
        "(1-year return, high, low, average volume) plus the last 10 trading days. "
        "Input should be a stock ticker symbol (e.g., 'AAPL')."
    )

    def _run(self, ticker: str) -> str:
        import yfinance as yf

        hist = yf.Ticker(ticker).history(period="1y")
        if hist.empty:
            return f"Error: Could not find data for ticker {ticker}."

        first, last = hist["Close"].iloc[0], hist["Close"].iloc[-1]
        summary = (
            f"Ticker: {ticker}\n"
            f"Period: {hist.index[0].date()} to {hist.index[-1].date()}\n"
            f"1-year return: {(last / first - 1) * 100:.1f}%\n"
            f"1-year high: {hist['High'].max():.2f}, low: {hist['Low'].min():.2f}\n"
            f"Latest close: {last:.2f}\n"
            f"Average daily volume: {hist['Volume'].mean():,.0f}\n\n"
            f"Last 10 trading days:\n"
        )
        recent = hist[["Open", "High", "Low", "Close", "Volume"]].iloc[-10:].round(2)
        return summary + recent.to_string()


class TechnicalIndicatorTool(BaseTool):
    """Calculates technical indicators for a given stock."""
    name: str = "Technical_Indicator_Calculator"
    description: str = (
        "Calculates RSI, MACD, SMA-20 and Bollinger Bands for a stock over the last year "
        "and returns the most recent 5 days. Input should be a stock ticker symbol (e.g., 'AAPL')."
    )

    def _run(self, ticker: str) -> str:
        import pandas_ta  # noqa: F401  (registers the .ta accessor on DataFrames)
        import yfinance as yf

        hist = yf.Ticker(ticker).history(period="1y")
        if hist.empty:
            return f"Error: Could not find data for ticker {ticker}."

        hist.ta.rsi(append=True)
        hist.ta.macd(append=True)
        hist.ta.sma(length=20, append=True)
        hist.ta.bbands(length=20, append=True)  # standard 20-day bands (library default is 5)
        return hist.drop(columns=["Dividends", "Stock Splits"], errors="ignore").iloc[-5:].round(2).to_string()


class EconomicResearcherTool(BaseTool):
    """Performs internet searches for financial news and sentiment."""
    name: str = "Economic_Researcher"
    description: str = (
        "Performs internet searches for financial news, sentiment, and "
        "macroeconomic factors about a provided company. "
        "Input should be a targeted search query (e.g., 'Apple Inc. investor sentiment last 6 months'). "
        "**Crucially, you must focus on trusted sources published within the last 6-12 months.** Avoid wikis, forums, or blogs."
    )

    def _run(self, query: str) -> str:
        try:
            from ddgs import DDGS

            with DDGS() as ddgs:
                results = list(ddgs.text(query, max_results=5))
            if not results:
                return "No results found."
            return "\n".join(
                f"Result {i + 1}:\n"
                f"  Title: {r.get('title', 'N/A')}\n"
                f"  Snippet: {r.get('body', 'N/A')}\n"
                f"  URL: {r.get('href', 'N/A')}\n"
                for i, r in enumerate(results)
            )
        except Exception as e:
            return f"An error occurred during the search: {e}"


class FinancialReportFormatter(BaseTool):
    """Wraps the analysis in a consistent Markdown report.

    This runs as plain code, not an LLM decision: formatting has one right
    answer, so it should be guaranteed rather than requested in a prompt.
    """
    name: str = "Financial_Report_Formatter"
    description: str = "Formats analysis text into a Markdown financial report with a disclaimer."

    def _run(self, data: str) -> str:
        # Escape any $ that isn't already escaped, so Streamlit doesn't render it as math.
        safe = re.sub(r"(?<!\\)\$", r"\\$", data.strip())
        return f"# Financial Report\n\n## Analysis Summary\n{safe}\n\n## Disclaimer\n{DISCLAIMER}\n"


class MemoryTool(BaseTool):
    """Saves and retrieves past financial reports per ticker in a JSON file."""
    name: str = "Memory_Tool"
    description: str = (
        "Used to save and retrieve past financial reports to provide long-term context. "
        "Use action='retrieve' with a ticker to fetch past reports. "
        "Use action='save' with a ticker and report to store a new report."
    )
    file_path: str = "report_memory.json"

    def _load(self) -> dict:
        if not os.path.exists(self.file_path):
            return {}
        with open(self.file_path, "r") as f:
            return json.load(f)

    def save(self, ticker: str, report: str) -> str:
        memory = self._load()
        memory.setdefault(ticker.upper(), []).append(report)
        with open(self.file_path, "w") as f:
            json.dump(memory, f, indent=2)
        return f"Report for {ticker.upper()} saved successfully."

    def retrieve(self, ticker: str, last_n: int = 2) -> str:
        reports = self._load().get(ticker.upper(), [])
        if not reports:
            return f"No past reports found for {ticker.upper()}."
        return "\n---\n".join(reports[-last_n:])  # only the most recent, to limit tokens

    def _run(self, action: str, ticker: Optional[str] = None, report: Optional[str] = None) -> str:
        if not ticker:
            return "Error: a 'ticker' is required."
        if action == "save":
            return self.save(ticker, report) if report else "Error: 'save' requires a 'report'."
        if action == "retrieve":
            return self.retrieve(ticker)
        return "Error: Invalid action. Use 'save' or 'retrieve'."
